"""Assemble docs/guesser/REPORT.md from docs/guesser/results/*.json ONLY (no hand-typed numbers).  python -m guesser.eval.make_report"""
import json, math, os, sys
R = "docs/guesser/results"


def load(n):
    p = os.path.join(R, n)
    return json.load(open(p)) if os.path.exists(p) else None


def f(x, d=4):
    return "-" if x is None else (f"{x:.{d}f}" if isinstance(x, float) else str(x))


def main():
    L = ["# GUESSER REPORT (generated by guesser/eval/make_report.py from docs/guesser/results/*.json)", ""]
    acc = []
    e1, e2, e3, e4, e5 = (load(n) for n in ("e1_null.json", "e2_power.json", "e3_paper.json", "e4_ablation.json", "e5_perf.json"))
    tests = load("tests.json")
    # ── E1
    L += ["## E1 - null calibration (fair streams)", ""]
    if e1:
        m = e1.get("_meta", {})
        L += [f"Sizes actually run: {m.get('streams')} streams x {m.get('ticks')} ticks per generator, sessions of {m.get('session')} symbols "
              f"(the brief asked for >= 2000 streams x >= 100000 ticks; that is ~3 orders of magnitude more compute than this 1-core sandbox allows - "
              f"so the empirical type-I check below is only as strong as its Wilson interval says; the guarantee itself is the Ville bound proved in `guesser/mixture.py`).", "",
              "| generator | streams | scored | top1 | z | top3 | z | mean ll gain (nats) | streams ever >= ln100 | Wilson95 | ever >= ln(S/a) | sessions Bonf T2 | sessions e-BH T2 | max log BF | restarts |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        ok1 = True
        for g, r in e1.items():
            if g.startswith("_"):
                continue
            w = r["ever_wilson95"]
            L.append(f"| {g} | {r['streams']} | {r['scored']} | {f(r['top1'])} | {f(r['top1_z'],2)} | {f(r['top3'])} | {f(r['top3_z'],2)} | {r['mean_ll_gain_nats']:.2e} | "
                     f"{r['ever_reach_ln100_per_stream']} | [{w[0]:.3f}, {w[1]:.3f}] | {r['ever_reach_ln(session/alpha)_per_stream']} | "
                     f"{r['sessions_with_bonferroni_T2']}/{r['sessions']} | {r['sessions_with_ebh_T2_any_checkpoint']}/{r['sessions']} | {r['max_log_e_over_streams']:.2f} | {r['restarts_total']} |")
            ok1 &= (abs(r["top1_z"]) <= 3 and abs(r["top3_z"]) <= 3 and r["mean_ll_gain_nats"] <= 1e-3
                    and r["ever_reach_ln100_per_stream"] / r["streams"] <= 0.01 and r["sessions_with_bonferroni_T2"] / max(1, r["sessions"]) <= 0.01)
        L += ["", "Calibration curve (tier T0, 3-digit sets; bin, n, mean predicted, empirical hit rate):", ""]
        for g, r in e1.items():
            if not g.startswith("_"):
                L.append(f"* {g}: " + "; ".join(f"b{b}: n={n}, pred={p:.4f}, emp={h:.4f}" for b, n, p, h in r["calibration_k3"]))
        wmax = max(r["ever_wilson95"][1] for g, r in e1.items() if not g.startswith("_"))
        acc.append(("E1 passes at the stated alpha (point estimates: hit rates within 3 SE, ll gain <= 0, ever-T2 rate <= alpha)", ok1,
                    f"Wilson upper bound of the per-stream ever-reach rate is {wmax:.3f} at this sample size ({'conclusive' if wmax <= 0.01 * 3 else 'only weakly conclusive'} for alpha=0.01)"))
    else:
        L.append("_not run_")
    # ── E2
    L += ["", "## E2 - power and detection delay (planted structure)", ""]
    if e2:
        L += [f"Detection = first tick with log BF >= ln 100 (single-stream alpha 0.01); `Bonf20` = >= ln 2000 (alpha/20). Streams capped at {e2[next(k for k in e2 if not k.startswith('_'))]['nmax']} ticks; "
              "`det` = streams detected / run; delays are medians over detected streams only when more than half detected (else `-`). Seconds assume 1 tick/s (x2 for 2 s symbols).", "",
              "| stream | guesser det | median ticks | p90 | Bonf20 median | top3 after detection | V2 det | V2 median | V2 top3 |", "|---|---|---|---|---|---|---|---|---|"]
        wins = ties = loses = 0
        lag20 = None
        for nm, r in e2.items():
            if nm.startswith("_"):
                continue
            g, gb, v = r["guesser_ln100"], r["guesser_bonf20"], r.get("v2_ln100")
            t3 = r["guesser_top3_after"]; v3 = r.get("v2_top3_after", [])
            L.append(f"| {nm} | {g['detected']} | {f(g['median'],0)} | {f(g['p90'],0)} | {f(gb['median'],0)} | {f(sum(t3)/len(t3) if t3 else None)} | "
                     f"{v['detected'] if v else '-'} | {f(v['median'],0) if v else '-'} | {f(sum(v3)/len(v3) if v3 else None) if v else '-'} |")
            if v and r["v2_supports"]:
                gd = sum(x is not None for x in g["all"]); vd = sum(x is not None for x in v["all"])
                gm, vm = g["median"], v["median"]
                if gd > vd or (gd == vd and (gm is not None and (vm is None or gm <= vm * 1.0))):
                    wins += 1
                elif gd == vd and gm == vm:
                    ties += 1
                else:
                    loses += 1
            if nm == "lagcopy lag=5 p=0.2":
                lag20 = g
        L += ["", f"Versus the existing V2 stack on the families V2 supports: guesser no worse on {wins} (incl. ties {ties}), worse on {loses}."]
        acc.append(("20% lag-copy detected (reported delay) and no worse than V2 on the planted families V2 supports", loses == 0 and lag20 is not None and lag20["median"] is not None,
                    f"lag-5 p=0.2: detected {lag20['detected'] if lag20 else '-'}, median {f(lag20['median'],0) if lag20 else '-'} ticks; worse than V2 on {loses} families"))
    else:
        L.append("_not run_")
    # ── E3
    L += ["", "## E3 - paper trading (Deriv-like payout r=(1-m)*10/k, 1 h = 3600 ticks, max stake 50, min stake 0.35, start 100)", ""]
    if e3:
        def tbl(sec, title):
            L.append(f"**{title}**")
            L.extend(["", "| scenario | runs | trades/h | win rate | break-even | P&L mean | P&L p05 | P&L median | P&L p95 | reach 2x | probe net mean | probe net worst | evidence trades | first trade tick | first T2 tick | bust |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"])
            for k, a in e3[sec].items():
                L.append(f"| {k} | {a['runs']} | {a['trades_per_hour_mean']:.0f} | {f(a['win_rate'])} | {f(a['breakeven'])} | {a['pnl_mean']:.2f} | {a['pnl_p05']:.2f} | {a['pnl_median']:.2f} | {a['pnl_p95']:.2f} | {a['reach_2x_frac']:.2f} | {a['probe_net_mean']:.2f} | {a['probe_net_worst']:.2f} | {a['evidence_trades_mean']:.1f} | {f(a['first_trade_tick_median'],0)} | {f(a['first_t2_tick_median'],0)} | {a['bust_frac']:.2f} |")
            L.append("")
        tbl("fair", "Fair streams (PCG64), latency 0, margin sweep"); tbl("latency", "Fair streams, margin 5%, latency 0/1/2 ticks")
        tbl("planted", "Planted structure (margin 5%, latency 0)")
        L += ["**Bold play on a fair stream (start 100, target 200; theory: success <= start/target = 0.5, shrinking with the margin)**", "", "| margin | bold success | flat-min-stake success |", "|---|---|---|"]
        for k, r in e3["bold"].items():
            L.append(f"| {k} | {r['bold']['success']:.3f} (n={r['bold']['runs']}) | {r['flat']['success']:.3f} (n={r['flat']['runs']}) |")
        fp = e3["fair"]
        worst = max((a["probe_net_worst"] for k, a in fp.items() if k.endswith(" probe")), default=0)
        probe_ok = all(-a["probe_net_worst"] <= 5.0 + 1e-6 for k, a in fp.items() if k.endswith(" probe"))
        acc.append(("Probe budget never exceeded in the paper runs (cap = 5% of 100)", probe_ok, f"worst net probe loss {min(a['probe_net_worst'] for k, a in fp.items() if k.endswith(' probe')):.2f}"))
        ft = [a["first_trade_tick_median"] for k, a in fp.items() if k.endswith(" probe")]
        acc.append(("Probe mode starts trading immediately (first trade tick)", all(x is not None and x <= 5 for x in ft), f"median first trade tick(s): {ft}"))
    else:
        L.append("_not run_")
    # ── E4
    L += ["", "## E4 - ablations", ""]
    if e4:
        m = e4["_meta"]
        L += [f"Fair: {m['streams']} streams x {m['ticks']} ticks per variant (max log BF kept, so any alpha can be read off); power: {m['seeds']} seeds, cap {m['nmax']} ticks, delay at ln 100 (`None` = not detected).", "",
              "| variant | null ever >= ln100 | ever >= ln20 | max null log BF | bias .12 | lagcopy5 .2 | markov2 .1 |", "|---|---|---|---|---|---|---|"]
        for k, r in e4.items():
            if k.startswith("_"):
                continue
            p = r["power_delay_ticks"]
            L.append(f"| {k} | {r['null_ever_ln100']}/{r['null_streams']} | {r['null_ever_ln20']}/{r['null_streams']} | {r['null_max']:.2f} | {p['bias .12']} | {p['lagcopy5 .2']} | {p['markov2 .1']} |")
        L.append("\nNot varied (not implemented as knobs): window sizes of Fw and tier thresholds beyond what the `ever >= ln20 / ln100` columns already show.")
    else:
        L.append("_not run_")
    # ── E5
    L += ["", "## E5 - performance", ""]
    if e5:
        pt, mem, bt = e5["per_tick"], e5["memory"], e5["boot"]
        L += [f"* per tick (`SymbolGuesser.on_tick`, all experts + shadow scoring + calibrator feed): p50 {pt['on_tick_ms_p50']:.3f} ms, p99 {pt['on_tick_ms_p99']:.3f} ms, max {pt['on_tick_ms_max']:.3f} ms over {pt['ticks']} ticks",
              f"* per scan per symbol (`view`: menu probabilities + calibration): p50 {pt['view_ms_p50']:.3f} ms, p99 {pt['view_ms_p99']:.3f} ms",
              f"* memory per symbol: tables {mem['table_bytes_per_symbol']} bytes (after 30k ticks: {mem['table_bytes_after_30k_ticks']}, bounded = {mem['bounded']}); traced incl. Python objects {mem['traced_bytes_per_symbol_incl_python_objects']:.0f} bytes",
              f"* boot with simulated paged history ({bt['symbols']} symbols, {bt['history_ticks']} ticks each, {bt['rtt_s']} s RTT per request): first symbol ready {bt['first_symbol_ready_s']:.1f} s, all ready {bt['all_symbols_ready_s']:.1f} s, first trade (probe) {bt['first_trade_after_boot_s_excl_waiting_for_next_tick']:.1f} s after boot ({bt['buys_in_first_scan']} buy in the first scan)", f"* {bt['note']}"]
        acc.append(("<= 2 ms p99 per tick per symbol; bounded memory", pt["on_tick_ms_p99"] <= 2.0 and mem["bounded"], f"p99 {pt['on_tick_ms_p99']:.3f} ms, bounded={mem['bounded']}"))
        acc.append(("Time to first eligible trade <= 3 min in the simulated run", bt["first_trade_after_boot_s_excl_waiting_for_next_tick"] <= 180, f"{bt['first_trade_after_boot_s_excl_waiting_for_next_tick']:.1f} s (plus the bot's own session/trade-window gates)"))
    else:
        L.append("_not run_")
    # ── acceptance
    L += ["", "## Acceptance criteria", "", "| criterion | result | detail |", "|---|---|---|"]
    if tests:
        acc.append(("Brute-force vs online mixture agree to 1e-9; no look-ahead; DP/Kelly/probe-budget tests", tests.get("guesser_tests_pass", False), tests.get("note", "")))
        acc.append(("With GUESSER_MODE=0 the existing test results equal the Phase 0 baseline", tests.get("flag_off_equals_baseline", False), tests.get("baseline_note", "")))
    for name, ok, detail in acc:
        L.append(f"| {name} | {'PASS' if ok else 'FAIL / INCONCLUSIVE'} | {detail} |")
    os.makedirs("docs/guesser", exist_ok=True)
    open("docs/guesser/REPORT.md", "w").write("\n".join(L) + "\n")
    print("wrote docs/guesser/REPORT.md")


if __name__ == "__main__":
    main()
